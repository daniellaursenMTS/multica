// Portfolio: the ClickUp intake list and the Opus hub projects in one overview, grouped by
// status like ClickUp. A project with a hub also shows its role diamond and links to the chat.
// All data is generated outside Multica (matas-ai-automation: portfolio/sync_intake.py,
// diamond/render_views.py) and served read-only from /diamond-views.

type RoleCode = "bo" | "po" | "plo" | "to";
interface Row {
  source: "clickup" | "hub";
  id: string;
  name: string;
  url: string | null;
  status: string;
  status_color?: string;
  assignees: { name?: string; initials?: string; color?: string }[];
  priority: string | null;
  start_date: string | null;
  due_date: string | null;
  updated: string | null;
  description: string;
  subtasks: number;
  fields: Record<string, unknown>;
  hub?: string | null;
  demo?: boolean;
  notes?: number;
  diamond?: Record<RoleCode, { person: string | null; state: string; text: string }>;
}
interface Portfolio { synced_at: string | null; as_of: string; rows: Row[] }
interface Index {
  as_of: string;
  accounts: Record<string, string>;
  people: { name: string; slug: string; roles: { project: string; role: RoleCode }[] }[];
}

const PROJECT_CHAT_AGENT_NAME = "Projekt-chat";
const STATUS_ORDER = ["stopped", "review", "in progress", "open"];
const STATUS_COLOR: Record<string, string> = { stopped: "#d33d44", review: "#5f55ee", "in progress": "#1090e0", open: "#87909e" };
const ROLE_NAME: Record<RoleCode, string> = { bo: "Business Owner", po: "Product Owner", plo: "Platform Owner", to: "Technical Owner" };
const STATE_TEXT: Record<string, string> = { updated: "opdateret", due: "snart", overdue: "bagud", waiting: "afventer", vacant: "ikke besat" };
const FIELD_ROWS: [string, string][] = [
  ["wof", "💡 WOF Score"], ["urgency", "Urgency Score"], ["cv", "CV Score (Commercial value)"], ["sw", "SW Score (Smarter Work)"],
  ["ts", "TS Score (T-shirt size)"], ["tshirt_size", "T-shirt Size"], ["smarter_work", "Smarter Work"],
  ["commercial_value", "Commercial Value"], ["activation_channel", "Activation channel / Connector"],
  ["manual_handling_time", "Manual handling time"], ["saved_time", "Saved time per workflow"],
  ["trigger_type", "Trigger type"], ["success_metrics", "Success metrics"],
];

function useText(url: string | null) {
  const [text, setText] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    if (!url) return;
    let live = true;
    setText(null);
    setError(null);
    fetch(url, { cache: "no-store", credentials: "include" })
      .then(async (r) => (r.ok ? r.text() : Promise.reject(new Error(await r.text()))))
      .then((t) => live && setText(t))
      .catch((e: Error) => live && setError(e.message || "Kunne ikke hente data."));
    return () => {
      live = false;
    };
  }, [url]);
  return { text, error };
}

/** Diagrams are generated by our own renderer, which escapes every text node. */
function Diagram({ url, label }: { url: string; label: string }) {
  const { text, error } = useText(url);
  if (error) return <p className="text-sm text-muted-foreground">{error}</p>;
  if (!text) return <div className="h-64 animate-pulse rounded-lg bg-muted" aria-label={`Henter ${label}`} />;
  return (
    <div className="overflow-x-auto rounded-lg border bg-[#F7F6F5]">
      <div className="min-w-[960px] [&_svg]:block [&_svg]:h-auto [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: text }} />
    </div>
  );
}

const show = (v: unknown) =>
  v === null || v === undefined || v === "" || (Array.isArray(v) && v.length === 0) ? "—" : Array.isArray(v) ? v.join(", ") : String(v);
const date = (d: string | null) => (d ? new Date(d).toLocaleDateString("da-DK", { day: "numeric", month: "short", year: "numeric" }) : "—");

function StatusPill({ status, color }: { status: string; color?: string }) {
  return (
    <span className="inline-flex items-center rounded px-2 py-0.5 text-xs font-semibold uppercase tracking-wide text-white"
      style={{ background: color || STATUS_COLOR[status] || "#87909e" }}>
      {status}
    </span>
  );
}

function Avatars({ people }: { people: Row["assignees"] }) {
  if (!people.length) return <span className="text-muted-foreground">—</span>;
  return (
    <span className="flex -space-x-1">
      {people.map((p, i) => (
        <span key={i} title={p.name} className="grid size-6 place-items-center rounded-full border-2 border-background text-[10px] font-semibold text-white"
          style={{ background: p.color || "#d33d44" }}>
          {p.initials || (p.name || "?").slice(0, 2).toUpperCase()}
        </span>
      ))}
    </span>
  );
}

function Overview({ rows, open }: { rows: Row[]; open: (id: string) => void }) {
  const groups = STATUS_ORDER.map((s) => ({ s, items: rows.filter((r) => r.status === s) })).concat(
    [{ s: "andet", items: rows.filter((r) => !STATUS_ORDER.includes(r.status)) }],
  ).filter((g) => g.items.length);
  const [closed, setClosed] = useState<Record<string, boolean>>({});
  return (
    <div className="flex flex-col gap-6">
      {groups.map(({ s, items }) => (
        <section key={s} aria-labelledby={`grp-${s}`}>
          <button type="button" id={`grp-${s}`} onClick={() => setClosed((c) => ({ ...c, [s]: !c[s] }))}
            className="mb-2 flex items-center gap-3 text-sm" aria-expanded={!closed[s]}>
            <span className="text-muted-foreground">{closed[s] ? "▸" : "▾"}</span>
            <StatusPill status={s} color={items[0]?.status_color} />
            <span className="text-muted-foreground">{items.length}</span>
          </button>
          {!closed[s] && (
            <div className="overflow-x-auto rounded-lg border">
              <table className="w-full min-w-[860px] text-sm">
                <thead className="text-left text-xs text-muted-foreground">
                  <tr className="border-b">
                    <th className="px-3 py-2 font-medium">Navn</th><th className="px-3 py-2 font-medium">Ansvarlig</th>
                    <th className="px-3 py-2 font-medium">Due date</th><th className="px-3 py-2 font-medium">Team</th>
                    <th className="px-3 py-2 font-medium">Priority</th><th className="px-3 py-2 text-right font-medium">💡 WOF</th>
                    <th className="px-3 py-2 text-right font-medium">CV</th><th className="px-3 py-2 text-right font-medium">SW</th>
                  </tr>
                </thead>
                <tbody>
                  {items.map((r) => (
                    <tr key={r.id} onClick={() => open(r.id)} className="cursor-pointer border-b last:border-0 hover:bg-accent/50">
                      <td className="px-3 py-2">
                        <button type="button" onClick={(e) => { e.stopPropagation(); open(r.id); }} className="text-left font-medium hover:underline focus-visible:outline-2">
                          {r.hub && <span title="Har diamant og projekt-chat" className="mr-1.5 text-[#CF022D]">◇</span>}
                          {r.name}
                        </button>
                        {r.demo && <span className="ml-2 rounded bg-muted px-1.5 py-0.5 text-[10px] uppercase">demo</span>}
                        {r.subtasks > 0 && <span className="ml-2 text-xs text-muted-foreground">↳ {r.subtasks}</span>}
                      </td>
                      <td className="px-3 py-2"><Avatars people={r.assignees} /></td>
                      <td className="px-3 py-2 tabular-nums">{date(r.due_date)}</td>
                      <td className="px-3 py-2">
                        {((r.fields.team as string[]) || []).map((t) => (
                          <span key={t} className="mr-1 rounded bg-muted px-1.5 py-0.5 text-xs">{t}</span>
                        ))}
                      </td>
                      <td className="px-3 py-2 capitalize">{show(r.priority)}</td>
                      <td className="px-3 py-2 text-right tabular-nums">{show(r.fields.wof)}</td>
                      <td className="px-3 py-2 text-right tabular-nums">{show(r.fields.cv)}</td>
                      <td className="px-3 py-2 text-right tabular-nums">{show(r.fields.sw)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </section>
      ))}
    </div>
  );
}

function Detail({ row, back, chatHref }: { row: Row; back: () => void; chatHref: string | null }) {
  return (
    <div className="flex flex-col gap-6">
      <button type="button" onClick={back} className="self-start text-sm text-muted-foreground hover:text-foreground">← Alle projekter</button>
      <header className="flex flex-col gap-3">
        <div className="flex flex-wrap items-center gap-3">
          <h2 className="text-2xl font-semibold">{row.name}</h2>
          {row.demo && <span className="rounded bg-muted px-1.5 py-0.5 text-xs uppercase">demo</span>}
        </div>
        <dl className="grid grid-cols-[max-content_1fr] gap-x-6 gap-y-2 text-sm sm:grid-cols-[max-content_1fr_max-content_1fr]">
          <dt className="text-muted-foreground">Status</dt><dd><StatusPill status={row.status} color={row.status_color} /></dd>
          <dt className="text-muted-foreground">Ansvarlig</dt>
          <dd className="flex items-center gap-2"><Avatars people={row.assignees} />{row.assignees.map((a) => a.name).filter(Boolean).join(", ")}</dd>
          <dt className="text-muted-foreground">Datoer</dt><dd>{date(row.start_date)} → {date(row.due_date)}</dd>
          <dt className="text-muted-foreground">Priority</dt><dd className="capitalize">{show(row.priority)}</dd>
          <dt className="text-muted-foreground">Team</dt><dd>{show(row.fields.team)}</dd>
          <dt className="text-muted-foreground">Kilde</dt>
          <dd>
            {row.url ? <a href={row.url} target="_blank" rel="noreferrer" className="underline underline-offset-4">Åbn i ClickUp</a> : "Opus-hub"}
            {row.hub && ` · ${row.notes ?? 0} Opus-noter`}
          </dd>
        </dl>
      </header>

      {row.description && <p className="max-w-[75ch] whitespace-pre-line leading-relaxed">{row.description}</p>}

      {row.hub ? (
        <section className="flex flex-col gap-3" aria-labelledby="dia">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <h3 id="dia" className="text-sm font-medium">Diamanten</h3>
            {chatHref && (
              <AppLink href={chatHref} className="rounded-md border px-3 py-1.5 text-sm font-medium hover:bg-accent">Chat med projektet →</AppLink>
            )}
          </div>
          <ul className="grid gap-2 text-sm sm:grid-cols-2 lg:grid-cols-4">
            {(["bo", "po", "plo", "to"] as RoleCode[]).map((c) => {
              const r = row.diamond?.[c];
              return (
                <li key={c} className="rounded-md border px-3 py-2">
                  <div className="text-xs text-muted-foreground">{ROLE_NAME[c]}</div>
                  <div className="font-medium">{r?.person || "ikke besat"}</div>
                  <div className={`text-xs ${r?.state === "overdue" ? "text-[#CF022D] font-medium" : "text-muted-foreground"}`}>
                    {STATE_TEXT[r?.state || "waiting"]} · {r?.text}
                  </div>
                </li>
              );
            })}
          </ul>
          <Diagram url={`/diamond-views/${row.hub}.svg`} label="diamant" />
          {chatHref && <p className="text-xs text-muted-foreground">I chatten: skriv fx «Hvad er status på {row.name.split(" (")[0]}?» — svaret kommer i din rolles sprog, med kilder.</p>}
        </section>
      ) : (
        <p className="rounded-md border border-dashed px-4 py-3 text-sm text-muted-foreground">
          Ingen Opus-hub endnu. Diamant og projekt-chat kommer, når projektet får sin første Opus-note — eller når det kobles til en hub i roster.json (clickup_task).
        </p>
      )}

      <section aria-labelledby="flds">
        <h3 id="flds" className="mb-2 text-sm font-medium">Felter</h3>
        <dl className="divide-y rounded-lg border text-sm">
          {FIELD_ROWS.map(([k, label]) => (
            <div key={k} className="grid grid-cols-[minmax(0,16rem)_1fr] gap-4 px-3 py-2">
              <dt className="text-muted-foreground">{label}</dt>
              <dd className="tabular-nums">{show(row.fields[k])}</dd>
            </div>
          ))}
        </dl>
      </section>
    </div>
  );
}

function PortfolioPage() {
  const router = useRouter();
  const params = useSearchParams();
  const email = useAuthStore((s) => s.user?.email ?? null);
  const workspace = useCurrentWorkspace();
  const p = useWorkspacePaths();
  const { data: agents } = useQuery({ ...agentListOptions(workspace?.id ?? ""), enabled: !!workspace?.id });
  const chatAgent = agents?.find((a) => !a.archived_at && a.name === PROJECT_CHAT_AGENT_NAME);
  const chatHref = chatAgent ? p.chatWithAgent(chatAgent.id) : null;

  const { text: pfText, error } = useText("/diamond-views/portfolio.json");
  const { text: idxText } = useText("/diamond-views/index.json");
  const pf = useMemo<Portfolio | null>(() => (pfText ? JSON.parse(pfText) : null), [pfText]);
  const index = useMemo<Index | null>(() => (idxText ? JSON.parse(idxText) : null), [idxText]);

  const tab = params.get("tab") === "mine" ? "mine" : "overview";
  const selected = params.get("project");
  const setParams = (next: Record<string, string | null>) => {
    const q = new URLSearchParams(params.toString());
    Object.entries(next).forEach(([k, v]) => (v ? q.set(k, v) : q.delete(k)));
    router.push(`?${q.toString()}`);
  };

  const me = index && email ? index.accounts[email.toLowerCase()] ?? null : null;
  const [person, setPerson] = useState<string | null>(null);
  const current = index?.people.find((x) => x.name === (person ?? me)) ?? index?.people[0] ?? null;
  const row = pf?.rows.find((r) => r.id === selected) ?? null;

  return (
    <div className="h-full min-h-0 flex-1 overflow-y-auto">
      <div className="flex flex-col gap-6 p-6">
        <header className="flex flex-wrap items-end justify-between gap-4">
          <div className="min-w-0">
            <h1 className="text-lg font-semibold">Portfolio</h1>
            <p className="text-sm text-muted-foreground">
              Alle projekter fra ClickUp-intake og Opus-hubben. ◇ betyder diamant og projekt-chat.
              {pf && ` Status pr. ${new Date(pf.as_of).toLocaleDateString("da-DK")}.`}
            </p>
          </div>
          <nav className="flex gap-1 rounded-md border p-0.5 text-sm" aria-label="Visning">
            {[["overview", "Oversigt"], ["mine", "Mine projekter"]].map(([k, label]) => (
              <button key={k} type="button" aria-pressed={tab === k} onClick={() => setParams({ tab: k === "mine" ? "mine" : null, project: null })}
                className={`rounded px-3 py-1 ${tab === k ? "bg-accent font-medium" : "text-muted-foreground hover:bg-accent/60"}`}>
                {label}
              </button>
            ))}
          </nav>
        </header>

        {error && <p className="text-sm text-muted-foreground">{error}</p>}
        {!pf && !error && <div className="h-64 animate-pulse rounded-lg bg-muted" aria-label="Henter portfolio" />}

        {pf && tab === "overview" && !row && <Overview rows={pf.rows} open={(id) => setParams({ project: id })} />}
        {pf && tab === "overview" && row && <Detail row={row} back={() => setParams({ project: null })} chatHref={chatHref} />}

        {tab === "mine" && index && (
          <section className="flex flex-col gap-3">
            <label className="flex items-center gap-2 self-end text-sm">
              <span className="text-muted-foreground">Person</span>
              <select id="portfolio-person" className="rounded-md border bg-background px-2 py-1" value={current?.name ?? ""}
                onChange={(e) => setPerson(e.target.value)}>
                {index.people.map((x) => (
                  <option key={x.slug} value={x.name}>{x.name}{x.name === me ? " (dig)" : ""}</option>
                ))}
              </select>
            </label>
            {current && <Diagram url={`/diamond-views/person-${current.slug}.svg`} label="projektoversigt" />}
          </section>
        )}

        {pf?.synced_at && (
          <p className="text-xs text-muted-foreground">ClickUp synkroniseret {new Date(pf.synced_at).toLocaleString("da-DK")} (skrivebeskyttet).</p>
        )}
      </div>
    </div>
  );
}

// The page reads the URL's search params, which Next requires behind a Suspense boundary.
export default function Page() {
  return (
    <Suspense fallback={<div className="p-6"><div className="h-64 animate-pulse rounded-lg bg-muted" /></div>}>
      <PortfolioPage />
    </Suspense>
  );
}
