/** Use per project over the last 30 days: Multica's agent usage records (same query and cache as the
 *  Capex page) plus manual Capex posts tied to the project, such as its Claude Code sessions.
 *  Tokens = input + output; kroner are a list-price estimate. */
function useProjectUsage(rows: Row[], manual: CapexManual[]) {
  const workspace = useCurrentWorkspace();
  const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
  const ids = rows.map((r) => r.multica_project).filter((x): x is string => !!x);
  const res = useQueries({
    queries: ids.map((pid) => ({
      queryKey: ["capex-usage", workspace?.id, pid, tz],
      enabled: !!workspace?.id,
      staleTime: 5 * 60_000,
      queryFn: () => api.getDashboardUsageDaily({ days: 365, project_id: pid, tz }),
    })),
  });
  return useMemo(() => {
    const to = usageToday();
    const from = daysBefore(to, USAGE_DAYS - 1);
    const out = new Map<string, { tokens: number; usd: number; approx: boolean }>();
    ids.forEach((pid, i) => {
      const data = res[i]?.data as DashboardUsageDaily[] | undefined;
      const u = (data ?? []).filter((d) => d.date >= from && d.date <= to).reduce((a, d) => ({ ...a, tokens: a.tokens + d.input_tokens + d.output_tokens, usd: a.usd + estimateCost(d) }), { tokens: 0, usd: 0, approx: false });
      manual.filter((m) => m.project_id === pid).forEach((m) => {
        const extra = usageTotal(m, from, to); u.tokens += extra.tokens; u.usd += extra.usd; u.approx ||= extra.approx;
      });
      out.set(pid, u);
    });
    return out;
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [ids.join(","), res.map((q) => q.dataUpdatedAt).join(","), manual]);
}

