function PortfolioPage() {
  const router = useRouter();
  const params = useSearchParams();
  const email = useAuthStore((s) => s.user?.email ?? null);
  const workspace = useCurrentWorkspace();
  const p = useWorkspacePaths();
  const { data: agents } = useQuery({ ...agentListOptions(workspace?.id ?? ""), enabled: !!workspace?.id });
  const chatAgent = agents?.find((a) => !a.archived_at && a.name === PROJECT_CHAT_AGENT_NAME);
  const chatHref = chatAgent ? p.chatWithAgent(chatAgent.id) : null;
  const agentName = (id: string | null) => agents?.find((a) => a.id === id)?.name ?? "agent";

  const { text: pfText, error } = useText("/diamond-views/portfolio.json");
  const { text: idxText } = useText("/diamond-views/index.json");
  const pf = useMemo<Portfolio | null>(() => (pfText ? JSON.parse(pfText) : null), [pfText]);
  const index = useMemo<Index | null>(() => (idxText ? JSON.parse(idxText) : null), [idxText]);

  const tab = params.get("tab") === "mine" ? "mine" : "overview";
  const selected = params.get("project");
  const setParams = (next: Record<string, string | null>) => {
    const q = new URLSearchParams(params.toString());
    Object.entries(next).forEach(([k, v]) => (v ? q.set(k, v) : q.delete(k)));
    router.push(`?${q.toString()}`);
  };

  // Live from Multica: projects created in Portfolio (they carry an intake issue) and the intake
  // fields of hub projects. Generated rows (ClickUp, hubs) are the base; live data is merged in.
  const { data: live } = useQuery({
    queryKey: ["portfolio", "live", workspace?.id],
    enabled: !!workspace?.id,
    queryFn: async () => {
      const [projects, intakes] = await Promise.all([
        api.listProjects(),
        api.listIssues({ metadata: { pf_intake: true }, limit: 200 }),
      ]);
      return { projects: projects.projects, intakes: intakes.issues };
    },
  });
  const rows = useMemo<Row[]>(() => {
    if (!pf) return [];
    const intakeBy = new Map((live?.intakes ?? []).filter((i) => i.project_id).map((i) => [i.project_id as string, i]));
    const known = new Set(pf.rows.map((r) => r.multica_project).filter(Boolean) as string[]);
    const moved = new Set((live?.intakes ?? []).map((i) => i.metadata.pf_clickup_id).filter(Boolean) as string[]);
    const merged = pf.rows.filter((r) => !(r.source === "clickup" && moved.has(r.id))).map((r) => {
      const intake = r.multica_project ? intakeBy.get(r.multica_project) : undefined;
      if (!intake) return r;
      const extra = fieldsFromMeta(intake.metadata);
      return { ...r, intake_issue: intake.id, intake_meta: intake.metadata,
        status: (intake.metadata.pf_status as string) || r.status,
        fields: { ...r.fields, ...Object.fromEntries(Object.entries(extra).filter(([, v]) => v !== null)) } };
    });
    for (const pr of live?.projects ?? []) {
      const intake = intakeBy.get(pr.id);
      if (!intake || known.has(pr.id)) continue;
      merged.push({
        source: "multica", id: pr.id, name: pr.title, url: (intake.metadata.pf_clickup_url as string) || null,
        status: (intake.metadata.pf_status as string) || PROJECT_TO_PF[pr.status] || "open",
        assignees: [], priority: pr.priority === "none" ? null : pr.priority,
        start_date: pr.start_date?.slice(0, 10) ?? null, due_date: pr.due_date?.slice(0, 10) ?? null,
        updated: pr.updated_at, description: pr.description ?? "", subtasks: 0,
        fields: fieldsFromMeta(intake.metadata), multica_project: pr.id, intake_issue: intake.id, intake_meta: intake.metadata,
      });
    }
    return merged.filter((r) => r.status !== "closed");
  }, [pf, live]);
  const [creating, setCreating] = useState(false);

  const me = index && email ? index.accounts[email.toLowerCase()] ?? null : null;
  const [person, setPerson] = useState<string | null>(null);
  const current = index?.people.find((x) => x.name === (person ?? me)) ?? index?.people[0] ?? null;
  const row = rows.find((r) => r.id === selected) ?? null;
  const rowProject = live?.projects.find((x) => x.id === row?.multica_project) ?? null;

  return (
    <div className="h-full min-h-0 flex-1 overflow-y-auto">
      <div className="flex flex-col gap-6 p-6">
        <header className="flex flex-wrap items-end justify-between gap-4">
          <div className="min-w-0">
            <h1 className="text-lg font-semibold">Portfolio</h1>
            <p className="text-sm text-muted-foreground">
              Alle projekter fra ClickUp-intake og Opus-hubben. ◇ betyder diamant og projekt-chat.
              {pf && ` Status pr. ${new Date(pf.as_of).toLocaleDateString("da-DK")}.`}
            </p>
          </div>
          <nav className="flex gap-1 rounded-md border p-0.5 text-sm" aria-label="Visning">
            {[["overview", "Oversigt"], ["mine", "Mine projekter"]].map(([k, label]) => (
              <button key={k} type="button" aria-pressed={tab === k} onClick={() => setParams({ tab: k === "mine" ? "mine" : null, project: null })}
                className={`rounded px-3 py-1 ${tab === k ? "bg-accent font-medium" : "text-muted-foreground hover:bg-accent/60"}`}>
                {label}
              </button>
            ))}
          </nav>
        </header>

        {error && <p className="text-sm text-muted-foreground">{error}</p>}
        {!pf && !error && <div className="h-64 animate-pulse rounded-lg bg-muted" aria-label="Henter portfolio" />}

        {pf && tab === "overview" && !row && (
          <>
            {creating ? (
              <ProjectForm mode="create" onCancel={() => setCreating(false)}
                onDone={(id) => { setCreating(false); setParams({ project: id }); }} />
            ) : (
              <button type="button" onClick={() => setCreating(true)} className="self-start rounded-md border px-3 py-1.5 text-sm font-medium hover:bg-accent">
                + Nyt projekt
              </button>
            )}
            <Overview rows={rows} open={(id) => setParams({ project: id })} />
          </>
        )}
        {pf && tab === "overview" && row && <Detail row={row} back={() => setParams({ project: null })} chatHref={chatHref} agentName={agentName} agents={agents ?? []} project={rowProject} onMoved={(id) => setParams({ project: id })} />}

        {tab === "mine" && index && (
          <section className="flex flex-col gap-3">
            <label className="flex items-center gap-2 self-end text-sm">
              <span className="text-muted-foreground">Person</span>
              <select id="portfolio-person" className="rounded-md border bg-background px-2 py-1" value={current?.name ?? ""}
                onChange={(e) => setPerson(e.target.value)}>
                {index.people.map((x) => (
                  <option key={x.slug} value={x.name}>{x.name}{x.name === me ? " (dig)" : ""}</option>
                ))}
              </select>
            </label>
            {current && <Diagram url={`/diamond-views/person-${current.slug}.svg`} label="projektoversigt" />}
          </section>
        )}

        {pf?.synced_at && (
          <p className="text-xs text-muted-foreground">ClickUp synkroniseret {new Date(pf.synced_at).toLocaleString("da-DK")} (skrivebeskyttet).</p>
        )}
      </div>
    </div>
  );
}

