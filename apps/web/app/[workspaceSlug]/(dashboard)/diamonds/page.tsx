"use client";

import { useEffect, useMemo, useState } from "react";
import { useAuthStore } from "@multica/core/auth";

type RoleCode = "bo" | "po" | "plo" | "to";
interface Index {
  as_of: string;
  generated_at: string;
  accounts: Record<string, string>;
  people: { name: string; slug: string; roles: { project: string; role: RoleCode }[] }[];
  projects: { slug: string; name: string; pilot_start: string | null; notes: number; last_note: string | null }[];
}

const ROLE = { bo: "BO", po: "PO", plo: "PLO", to: "TO" } as const;

function useText(url: string | null) {
  const [text, setText] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    if (!url) return;
    let live = true;
    setText(null);
    setError(null);
    fetch(url, { cache: "no-store", credentials: "include" })
      .then(async (r) => (r.ok ? r.text() : Promise.reject(new Error(await r.text()))))
      .then((t) => live && setText(t))
      .catch((e: Error) => live && setError(e.message || "Kunne ikke hente diagrammet."));
    return () => {
      live = false;
    };
  }, [url]);
  return { text, error };
}

/** Diagrams are generated by our own renderer, which escapes every text node. */
function Diagram({ url, label }: { url: string | null; label: string }) {
  const { text, error } = useText(url);
  if (error) return <p className="text-sm text-muted-foreground">{error}</p>;
  if (!text) return <div className="h-64 animate-pulse rounded-lg bg-muted" aria-label={`Henter ${label}`} />;
  return (
    <div className="overflow-x-auto rounded-lg border bg-[#F7F6F5]">
      <div className="min-w-[960px] [&_svg]:block [&_svg]:h-auto [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: text }} />
    </div>
  );
}

export default function Page() {
  const email = useAuthStore((s) => s.user?.email ?? null);
  const { text: indexText, error } = useText("/diamond-views/index.json");
  const index = useMemo<Index | null>(() => (indexText ? (JSON.parse(indexText) as Index) : null), [indexText]);

  const me = index && email ? index.accounts[email.toLowerCase()] ?? null : null;
  const [person, setPerson] = useState<string | null>(null);
  const [project, setProject] = useState<string | null>(null);
  const current = index?.people.find((p) => p.name === (person ?? me)) ?? index?.people[0] ?? null;
  const mine = current ? [...new Set(current.roles.map((r) => r.project))] : [];
  const shown = project ?? mine[0] ?? index?.projects[0]?.slug ?? null;

  if (error) {
    return (
      <div className="p-6">
        <h1 className="text-lg font-semibold">Diamonds</h1>
        <p className="mt-2 text-sm text-muted-foreground">{error}</p>
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-6 p-6">
      <header className="flex flex-wrap items-end justify-between gap-4">
        <div className="min-w-0">
          <h1 className="text-lg font-semibold">Diamonds</h1>
          <p className="text-sm text-muted-foreground">
            Hvem i hvert projekts diamant har opdateret via Opus, og hvornår.
            {index && ` Status pr. ${new Date(index.as_of).toLocaleDateString("da-DK")}.`}
          </p>
        </div>
        {index && (
          <label className="flex items-center gap-2 text-sm">
            <span className="text-muted-foreground">Person</span>
            <select
              id="diamond-person"
              className="rounded-md border bg-background px-2 py-1"
              value={current?.name ?? ""}
              onChange={(e) => {
                setPerson(e.target.value);
                setProject(null);
              }}
            >
              {index.people.map((p) => (
                <option key={p.slug} value={p.name}>
                  {p.name}
                  {p.name === me ? " (dig)" : ""}
                </option>
              ))}
            </select>
          </label>
        )}
      </header>

      <section className="flex flex-col gap-3" aria-labelledby="mine">
        <h2 id="mine" className="text-sm font-medium">
          {current?.name === me ? "Mine projekter" : `${current?.name ?? ""}s projekter`}
        </h2>
        <Diagram url={current ? `/diamond-views/person-${current.slug}.svg` : null} label="projektoversigt" />
      </section>

      <section className="flex flex-col gap-3" aria-labelledby="diamond">
        <div className="flex flex-wrap items-center gap-2">
          <h2 id="diamond" className="mr-2 text-sm font-medium">
            Diamant
          </h2>
          {index?.projects.map((p) => {
            const roles = current?.roles.filter((r) => r.project === p.slug).map((r) => ROLE[r.role]) ?? [];
            return (
              <button
                key={p.slug}
                type="button"
                onClick={() => setProject(p.slug)}
                aria-pressed={shown === p.slug}
                className={`rounded-md border px-3 py-1 text-sm focus-visible:outline-2 ${
                  shown === p.slug ? "border-foreground bg-accent font-medium" : "text-muted-foreground hover:bg-accent/60"
                }`}
              >
                {p.name}
                {roles.length > 0 && <span className="ml-1 text-xs opacity-70">· {roles.join(" · ")}</span>}
              </button>
            );
          })}
        </div>
        <Diagram url={shown ? `/diamond-views/${shown}.svg` : null} label="diamant" />
      </section>

      {index && (
        <p className="text-xs text-muted-foreground">
          Diagrammerne genereres af diamond_status.py ud fra rollelisten og Opus-noterne. Sidst genereret{" "}
          {new Date(index.generated_at).toLocaleString("da-DK")}.
        </p>
      )}
    </div>
  );
}
