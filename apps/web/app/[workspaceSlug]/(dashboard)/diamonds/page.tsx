function useText(url: string | null) {
  const [text, setText] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    if (!url) return;
    let live = true;
    setText(null);
    setError(null);
    fetch(url, { cache: "no-store", credentials: "include" })
      .then(async (r) => (r.ok ? r.text() : Promise.reject(new Error(await r.text()))))
      .then((t) => live && setText(t))
      .catch((e: Error) => live && setError(e.message || "Kunne ikke hente data."));
    return () => {
      live = false;
    };
  }, [url]);
  return { text, error };
}

/** Diagrams are generated by our own renderer, which escapes every text node. */
function Diagram({ url, label }: { url: string; label: string }) {
  const { text, error } = useText(url);
  if (error) return <p className="text-sm text-muted-foreground">{error}</p>;
  if (!text) return <div className="h-64 animate-pulse rounded-lg bg-muted" aria-label={`Henter ${label}`} />;
  return (
    <div className="overflow-x-auto rounded-lg border bg-[#F7F6F5]">
      <div className="min-w-[960px] [&_svg]:block [&_svg]:h-auto [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: text }} />
    </div>
  );
}

