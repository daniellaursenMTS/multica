const ago = (iso: string) => {
  const d = Math.round((Date.now() - new Date(iso).getTime()) / 86_400_000);
  return d <= 0 ? "i dag" : d === 1 ? "i går" : `${d} dage siden`;
};

/** Every issue in the project, live from Multica — newest activity first. Opus notes, agent tasks
 *  and anything created from the project all land here, so this is the project's history. */
function History({ projectId, agentName }: { projectId: string; agentName: (id: string | null) => string }) {
  const p = useWorkspacePaths();
  const me = useAuthStore((s) => s.user?.id ?? null);
  const { data, isLoading, error } = useQuery({
    queryKey: ["portfolio", "project-issues", projectId],
    queryFn: async () => {
      const all: Issue[] = [];
      for (let offset = 0; offset < 500; offset += 100) {
        const res = await api.listIssues({ project_id: projectId, limit: 100, offset });
        all.push(...res.issues);
        if (res.issues.length < 100 || all.length >= res.total) break;
      }
      return all.sort((a, b) => (b.updated_at ?? "").localeCompare(a.updated_at ?? ""));
    },
  });
  const [all, setAll] = useState(false);
  if (isLoading) return <div className="h-24 animate-pulse rounded-lg bg-muted" aria-label="Henter historik" />;
  if (error) return <p className="text-sm text-muted-foreground">Kunne ikke hente projektets issues.</p>;
  const issues = data ?? [];
  if (!issues.length) return <p className="text-sm text-muted-foreground">Ingen issues i projektet endnu.</p>;
  const counts = issues.reduce<Record<string, number>>((m, i) => ((m[i.status] = (m[i.status] ?? 0) + 1), m), {});
  const shown = all ? issues : issues.slice(0, 15);
  return (
    <div className="flex flex-col gap-2">
      <p className="text-xs text-muted-foreground">
        {issues.length} issues · {Object.entries(counts).map(([k, v]) => `${v} ${k.replace("_", " ")}`).join(" · ")}
      </p>
      <ol className="divide-y rounded-lg border">
        {shown.map((i) => (
          <li key={i.id} className="grid grid-cols-[auto_1fr_auto] items-center gap-3 px-3 py-2 text-sm">
            <span className="size-2 rounded-full" style={{ background: ISSUE_STATUS_COLOR[i.status] ?? "#87909e" }} title={i.status_name ?? i.status} />
            <div className="min-w-0">
              <AppLink href={p.issueDetail(i.id)} className="block truncate font-medium hover:underline">
                <span className="mr-2 font-mono text-xs text-muted-foreground">{i.identifier}</span>{i.title}
              </AppLink>
              <span className="text-xs text-muted-foreground">
                {i.status_name ?? i.status.replace("_", " ")}
                {i.assignee_id && ` · ${i.assignee_type === "agent" ? agentName(i.assignee_id) : i.assignee_id === me ? "dig" : "medlem"}`}
              </span>
            </div>
            <span className="whitespace-nowrap text-xs tabular-nums text-muted-foreground">{i.updated_at ? ago(i.updated_at) : ""}</span>
          </li>
        ))}
      </ol>
      {issues.length > 15 && (
        <button type="button" onClick={() => setAll((v) => !v)} className="self-start text-sm text-muted-foreground hover:text-foreground">
          {all ? "Vis færre" : `Vis alle ${issues.length}`}
        </button>
      )}
    </div>
  );
}

/** Create an issue in the project and hand it to an agent. It lands in the history below at once. */
function NewTask({ projectId, projectName, agents }: { projectId: string; projectName: string; agents: Agent[] }) {
  const workspace = useCurrentWorkspace();
  const p = useWorkspacePaths();
  const qc = useQueryClient();
  const [open, setOpen] = useState(false);
  const [title, setTitle] = useState("");
  const [description, setDescription] = useState("");
  const [agentId, setAgentId] = useState("");
  const [startNow, setStartNow] = useState(true);
  const [created, setCreated] = useState<Issue | null>(null);
  const choosable = agents.filter((a) => !a.archived_at).sort((a, b) => a.name.localeCompare(b.name, "da"));
  const agent = choosable.find((a) => a.id === agentId);
  const create = useMutation({
    mutationFn: () =>
      api.createIssue({
        title: title.trim(),
        description: description.trim() || undefined,
        project_id: projectId,
        status: agentId && startNow ? "todo" : "backlog",
        ...(agentId ? { assignee_type: "agent" as const, assignee_id: agentId } : {}),
      }),
    onSuccess: (issue) => {
      setCreated(issue);
      setTitle("");
      setDescription("");
      qc.invalidateQueries({ queryKey: ["portfolio", "project-issues", projectId] });
      if (workspace?.id) qc.invalidateQueries({ queryKey: issueKeys.all(workspace.id) });
    },
  });

  if (!open) {
    return (
      <div className="flex flex-wrap items-center gap-3">
        <button type="button" onClick={() => { setOpen(true); setCreated(null); }}
          className="rounded-md border px-3 py-1.5 text-sm font-medium hover:bg-accent">+ Ny opgave</button>
        {created && (
          <span className="text-sm text-muted-foreground">
            Oprettet:{" "}
            <AppLink href={p.issueDetail(created.id)} className="font-medium text-foreground underline underline-offset-4">
              {created.identifier} {created.title}
            </AppLink>
          </span>
        )}
      </div>
    );
  }
  return (
    <form
      className="flex flex-col gap-3 rounded-lg border p-4"
      onSubmit={(e) => { e.preventDefault(); if (title.trim()) create.mutate(undefined, { onSuccess: () => setOpen(false) }); }}
    >
      <div className="text-sm font-medium">Ny opgave i {projectName}</div>
      <label className="flex flex-col gap-1 text-sm">
        <span className="text-muted-foreground">Titel</span>
        <input id="portfolio-task-title" required value={title} onChange={(e) => setTitle(e.target.value)}
          className="rounded-md border bg-background px-2 py-1.5" placeholder="Hvad skal der gøres?" autoFocus />
      </label>
      <label className="flex flex-col gap-1 text-sm">
        <span className="text-muted-foreground">Beskrivelse</span>
        <textarea id="portfolio-task-description" value={description} onChange={(e) => setDescription(e.target.value)} rows={4}
          className="rounded-md border bg-background px-2 py-1.5" placeholder="Baggrund, hvad er færdigt, hvad skal undgås …" />
      </label>
      <label className="flex flex-col gap-1 text-sm">
        <span className="text-muted-foreground">Agent</span>
        <select id="portfolio-task-agent" value={agentId} onChange={(e) => setAgentId(e.target.value)} className="rounded-md border bg-background px-2 py-1.5">
          <option value="">Ingen — gem kun opgaven</option>
          {choosable.map((a) => <option key={a.id} value={a.id}>{a.name}</option>)}
        </select>
        {agent?.description && <span className="text-xs text-muted-foreground">{agent.description}</span>}
      </label>
      {agentId && (
        <label className="flex items-center gap-2 text-sm">
          <input id="portfolio-task-start" type="checkbox" checked={startNow} onChange={(e) => setStartNow(e.target.checked)} />
          Start agenten nu
          <span className="text-xs text-muted-foreground">— ellers parkeres den i backlog, til du flytter den til todo</span>
        </label>
      )}
      {create.error && <p className="text-sm text-[#CF022D]">Kunne ikke oprette opgaven: {(create.error as Error).message}</p>}
      <div className="flex gap-2">
        <button type="submit" disabled={!title.trim() || create.isPending}
          className="rounded-md bg-foreground px-3 py-1.5 text-sm font-medium text-background disabled:opacity-50">
          {create.isPending ? "Opretter …" : agentId && startNow ? `Opret og start ${agent?.name ?? "agent"}` : "Opret opgave"}
        </button>
        <button type="button" onClick={() => setOpen(false)} className="rounded-md border px-3 py-1.5 text-sm">Annullér</button>
      </div>
    </form>
  );
}

/** Copy a ClickUp project into Multica: project + intake issue from its fields. ClickUp is only
 *  read — nothing is written back. Afterwards the Multica project replaces the ClickUp row. */
function MoveToMultica({ row, onMoved }: { row: Row; onMoved: (projectId: string) => void }) {
  const me = useAuthStore((s) => s.user?.id ?? null);
  const qc = useQueryClient();
  const [confirming, setConfirming] = useState(false);
  const move = useMutation({
    mutationFn: async () => {
      const f = row.fields;
      const num = (v: unknown) => (v === null || v === undefined || v === "" ? null : Number(v));
      const list = (v: unknown) => (Array.isArray(v) ? v.join(", ") : v ? String(v) : "");
      const priority = ({ urgent: "urgent", high: "high", normal: "medium", low: "low" } as const)[row.priority as "urgent" | "high" | "normal" | "low"] ?? "none";
      const project = await api.createProject({
        title: row.name, description: row.description || undefined, status: PF_TO_PROJECT[row.status] ?? "planned", priority,
        start_date: row.start_date ?? undefined, due_date: row.due_date ?? undefined,
        ...(me ? { lead_type: "member" as const, lead_id: me } : {}),
      });
      const intake = await api.createIssue({
        title: `Intake — ${row.name}`, project_id: project.id, status: "done",
        description: `Flyttet fra ClickUp ${new Date().toLocaleDateString("da-DK")}: ${row.url ?? row.id}\n\nPortfolio-felter ligger som metadata (pf_*). ClickUp er ikke ændret.`,
      });
      const meta: Record<string, IssueMetadataValue | null> = {
        pf_intake: true, pf_status: row.status, pf_clickup_id: row.id, pf_clickup_url: row.url ?? "",
        pf_tshirt_size: num(f.tshirt_size), pf_smarter_work: num(f.smarter_work), pf_commercial_value: num(f.commercial_value),
        pf_urgency: num(f.urgency), pf_team: list(f.team), pf_activation_channel: list(f.activation_channel),
        pf_manual_handling_time: num(f.manual_handling_time), pf_saved_time: num(f.saved_time),
        pf_trigger_type: list(f.trigger_type), pf_success_metrics: list(f.success_metrics),
      };
      for (const [k, v] of Object.entries(meta)) {
        if (v !== null && v !== "" && !(typeof v === "number" && Number.isNaN(v))) await api.setIssueMetadataKey(intake.id, k, v);
      }
      return project.id;
    },
    onSuccess: (projectId) => { qc.invalidateQueries({ queryKey: ["portfolio"] }); onMoved(projectId); },
  });
  if (!confirming) {
    return (
      <button type="button" onClick={() => setConfirming(true)} className="rounded-md border px-3 py-1.5 text-sm font-medium hover:bg-accent">
        Flyt til Multica
      </button>
    );
  }
  return (
    <div className="flex flex-col gap-2 rounded-lg border p-4 text-sm">
      <p>
        Opret <strong>{row.name}</strong> som Multica-projekt med felter, beskrivelse og datoer fra ClickUp? Derefter kan du oprette
        opgaver til agenter og redigere felterne her. <strong>ClickUp ændres ikke</strong> — luk eller arkivér opgaven dér selv, hvis den ikke
        skal bruges mere.
      </p>
      {move.error && <p className="text-[#CF022D]">Kunne ikke flytte: {(move.error as Error).message}</p>}
      <div className="flex gap-2">
        <button type="button" onClick={() => move.mutate()} disabled={move.isPending}
          className="rounded-md bg-foreground px-3 py-1.5 font-medium text-background disabled:opacity-50">
          {move.isPending ? "Flytter …" : "Ja, flyt til Multica"}
        </button>
        <button type="button" onClick={() => setConfirming(false)} className="rounded-md border px-3 py-1.5">Annullér</button>
      </div>
    </div>
  );
}

