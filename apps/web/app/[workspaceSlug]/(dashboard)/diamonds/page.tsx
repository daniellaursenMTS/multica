function StatusPill({ status, color }: { status: string; color?: string }) {
  return (
    <span className="inline-flex items-center rounded px-2 py-0.5 text-xs font-semibold uppercase tracking-wide text-white"
      style={{ background: color || STATUS_COLOR[status] || "#87909e" }}>
      {status}
    </span>
  );
}

function Avatars({ people }: { people: Row["assignees"] }) {
  if (!people.length) return <span className="text-muted-foreground">—</span>;
  return (
    <span className="flex -space-x-1">
      {people.map((p, i) => (
        <span key={i} title={p.name} className="grid size-6 place-items-center rounded-full border-2 border-background text-[10px] font-semibold text-white"
          style={{ background: p.color || "#d33d44" }}>
          {p.initials || (p.name || "?").slice(0, 2).toUpperCase()}
        </span>
      ))}
    </span>
  );
}

