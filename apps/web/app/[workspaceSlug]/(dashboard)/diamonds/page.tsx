function useText(url: string | null) {
  const [text, setText] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    if (!url) return;
    let live = true;
    setText(null);
    setError(null);
    fetch(url, { cache: "no-store", credentials: "include" })
      .then(async (r) => (r.ok ? r.text() : Promise.reject(new Error(await r.text()))))
      .then((t) => live && setText(t))
      .catch((e: Error) => live && setError(e.message || "Kunne ikke hente data."));
    return () => {
      live = false;
    };
  }, [url]);
  return { text, error };
}

/** Diagrams are generated by our own renderer, which escapes every text node. */
function Diagram({ url, label }: { url: string; label: string }) {
  const { text, error } = useText(url);
  if (error) return <p className="text-sm text-muted-foreground">{error}</p>;
  if (!text) return <div className="h-64 animate-pulse rounded-lg bg-muted" aria-label={`Henter ${label}`} />;
  return (
    <div className="overflow-x-auto rounded-lg border bg-[#F7F6F5]">
      <div className="min-w-[960px] [&_svg]:block [&_svg]:h-auto [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: text }} />
    </div>
  );
}

const show = (v: unknown) =>
  v === null || v === undefined || v === "" || (Array.isArray(v) && v.length === 0) ? "—" : Array.isArray(v) ? v.join(", ") : String(v);
const date = (d: string | null) => (d ? new Date(d).toLocaleDateString("da-DK", { day: "numeric", month: "short", year: "numeric" }) : "—");

function StatusPill({ status, color }: { status: string; color?: string }) {
  return (
    <span className="inline-flex items-center rounded px-2 py-0.5 text-xs font-semibold uppercase tracking-wide text-white"
      style={{ background: color || STATUS_COLOR[status] || "#87909e" }}>
      {status}
    </span>
  );
}

function Avatars({ people }: { people: Row["assignees"] }) {
  if (!people.length) return <span className="text-muted-foreground">—</span>;
  return (
    <span className="flex -space-x-1">
      {people.map((p, i) => (
        <span key={i} title={p.name} className="grid size-6 place-items-center rounded-full border-2 border-background text-[10px] font-semibold text-white"
          style={{ background: p.color || "#d33d44" }}>
          {p.initials || (p.name || "?").slice(0, 2).toUpperCase()}
        </span>
      ))}
    </span>
  );
}

